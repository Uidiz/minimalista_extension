// i18n.js — traduzioni dell'interfaccia (it, en, es, fr, de, pt).
// Le pagine caricano questo file dopo common.js; il service worker lo importa
// con importScripts per sanitizzare il campo `lang` delle impostazioni.
"use strict";

/* ============================================================
   Registro delle lingue
   ============================================================ */
const LANGUAGES = {
  it: { name: "Italiano",  locale: "it-IT" },
  en: { name: "English",   locale: "en-US" },
  es: { name: "Español",   locale: "es-ES" },
  fr: { name: "Français",  locale: "fr-FR" },
  de: { name: "Deutsch",   locale: "de-DE" },
  pt: { name: "Português", locale: "pt-PT" }
};

/* ============================================================
   Stato lingua
   ============================================================ */
let _storedLang = null;    // valore salvato nelle impostazioni ("auto" o codice)
let _resolvedLang = null;  // codice lingua effettivamente in uso

function resolveUILang(stored) {
  if (stored && stored !== "auto" && LANGUAGES[stored]) return stored;
  // "auto" / assente / non valido → lingua del browser se supportata
  const nav = (typeof navigator !== "undefined" && navigator.language || "it").toLowerCase();
  const base = nav.split("-")[0];
  return LANGUAGES[base] ? base : "it";
}

function setUILang(stored) {
  _storedLang = stored || "auto";
  _resolvedLang = resolveUILang(stored);
  if (typeof document !== "undefined" && document.documentElement) {
    document.documentElement.lang = localeTag();
  }
}

function uiLang() {
  if (!_resolvedLang) setUILang(_storedLang || "auto");
  return _resolvedLang;
}

function uiStoredLang() { return _storedLang || "auto"; }

// tag BCP-47 per la formattazione delle date (it-IT, en-US, …)
function localeTag() {
  const l = uiLang();
  return (LANGUAGES[l] && LANGUAGES[l].locale) || LANGUAGES.it.locale;
}

/* ============================================================
   Traduzione
   ============================================================ */
function t(key, vars) {
  const dict = I18N[uiLang()] || I18N.it;
  let s = dict[key] !== undefined ? dict[key] : (I18N.it[key] !== undefined ? I18N.it[key] : key);
  if (vars) {
    for (const k in vars) s = s.split("{" + k + "}").join(String(vars[k]));
  }
  return s;
}

/* ============================================================
   Applicazione delle traduzioni al DOM statico
   ------------------------------------------------------------
   - data-i18n        → textContent
   - data-i18n-html   → innerHTML (la traduzione contiene markup)
   - data-i18n-ph     → placeholder
   - data-i18n-title  → title
   - data-i18n-aria   → aria-label
   ============================================================ */
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}

